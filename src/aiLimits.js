/**
 * AIに読ませる量と、AIから受け取る量の上限をまとめた1枚です。
 *
 * ここにあるのは「変えても壊れないが、変えると結果が変わる」数だけです。どれも
 * 何かとの取引になっているので、値の隣にその取引を書いてあります。増やせば見落としが
 * 減る代わりに待ち時間と費用が増え、減らせばその逆になる、というだけの話ではありません。
 * たとえば見取り図の見出し数を削ると、待ち時間ではなく「節の並び順への指摘」が消えます。
 *
 * 逆に、ここに置かないものもあります。
 *   - モデルと推論強度は `codexProfiles.js`。用途ごとの選び方そのものが判断だからです。
 *   - サンドボックスや許可するアイテム種別は `codexAppServer.js`。調整つまみではなく、
 *     緩めてはいけない約束だからです。
 *   - 「返ってきた答えをどこまで受け取るか」はそれぞれのモジュールに残します。たとえば
 *     ペルソナ1項目の長さ（`persona.js` の `MAX_ITEM_CHARS`）は、モデルへ渡す量ではなく
 *     答えの検証なので、検証コードの隣にあるほうが読めます。
 *     ここにあるのは「モデルが読む量」と「モデルに返させる量」だけです。
 */

/* ---- AIレビュー ---------------------------------------------------- */

/**
 * 1周目に出させる指摘の上限。プロンプトの「Report at most …」へそのまま入ります。
 * 増やすほどレビュアーが読む量が増え、減らすほど見落とします。
 */
export const MAX_FINDINGS = 20;

/**
 * 見取り図（<document_outline>）に載せる見出しの数。
 * 削ると待ち時間ではなく「この節はここにあるべきではない」種の指摘が出なくなります。
 * 並び順の指摘は、全体を一度に見たときにしか出てこないからです。
 */
export const MAX_OUTLINE_HEADINGS = 80;

/**
 * 反証へ添え直す本文の長さ。1周目と同じスレッドなのでモデルは本文を読んでいますが、
 * 引用と本文の突き合わせだけは記憶ではなく目の前の文字で確かめてほしいので渡します。
 */
export const MAX_VERIFIED_SEGMENT_CHARS = 400;

/* ---- 指摘の配置（AIレビューの結果もここを通ります） ------------------ */

/**
 * 1回に受け取る配置の上限。超えた分は捨てて、件数だけを droppedPlacements として画面に出します。
 *
 * MAX_FINDINGS より大きくしてあります。AIレビューは「20件まで」と頼んだうえで、
 * 指摘の配置は同じ検証を通るので、レビュアーの走り書きから30件出ることもあるからです。
 * これを MAX_FINDINGS より小さくすると、頼んだ数だけ出た指摘が黙って切れます。
 */
export const MAX_PLACEMENTS = 30;

/** モデルへ渡す本文ブロックの数。長い文書でも1回のプロンプトに収めるための頭打ちです。 */
export const MAX_SEGMENTS = 600;

/** 1ブロックあたりの本文の長さ。これを超えるブロックは末尾を「…」で切ります。 */
export const MAX_SEGMENT_PROMPT_CHARS = 600;

/**
 * 引用の前後に添える文字数。ブラウザが同じ文字列を本文から見つけ直すための手がかりです。
 * 画面側が手で付けたコメントに保存する長さ（public/js/textAnchor.js）と揃えてあります。
 * 短くすると、同じ語が何度も出てくる文書で別の箇所に張り付きます。
 */
export const ANCHOR_CONTEXT_CHARS = 120;

/** レビュアーが一度に貼り付けられる指摘コメントの長さ。 */
export const MAX_NOTES_CHARS = 4_000;

/* ---- 翻訳・AIチャット ------------------------------------------------ */

/**
 * 1回のやり取りでモデルへ渡す本文の上限。文書全体を対象にした翻訳や会話もここで止まります。
 * Codexの入力上限そのものではなく、「これを超えたら文書を分けたほうが結果が良い」線です。
 */
export const MAX_TARGET_CHARS = 100_000;

/** レビュアーが1回に送れる質問の長さ。 */
export const MAX_MESSAGE_CHARS = 12_000;

/**
 * 選択範囲の前後として持ち回る文字数。翻訳の語義はここで決まることが多く、
 * `ANCHOR_CONTEXT_CHARS` より長いのは、こちらが読ませるため、あちらが探すためだからです。
 */
export const TARGET_CONTEXT_CHARS = 1_000;

/** 対象に添える見出し階層の深さ。これ以上深い階層は、位置の手がかりになりません。 */
export const MAX_HEADING_DEPTH = 12;

/**
 * 「単語として引く」か「文章として訳す」かの境目。
 * どちらでもない中途半端な長さでは、文章として訳したほうが外しません。
 */
export const TERM_MAX_CHARS = 80;
export const TERM_MAX_WORDS = 6;

/** 会話一覧に出す題名の長さ。超えた分は「…」にします。 */
export const CONVERSATION_TITLE_CHARS = 48;

/** 端末に持っておく翻訳キャッシュの件数。古いものから捨てます。 */
export const MAX_TRANSLATIONS = 500;

/* ---- AIチャットへ渡すレビューコメント -------------------------------- */

/**
 * チャットへ持っていくコメントの件数。
 * 話している箇所に付いたコメントを先に残し、あふれた分の件数はプロンプトへ書きます。
 */
export const MAX_CHAT_COMMENTS = 60;

/** コメント1件が指す本文の引用の長さ。 */
export const MAX_CHAT_QUOTE_CHARS = 300;

/** コメント1件の本文の長さ。 */
export const MAX_CHAT_COMMENT_CHARS = 800;

/* ---- 読み取りコンテキストと読み手ペルソナ ---------------------------- */

/**
 * 読み取りコンテキスト1つの長さ。プロジェクト側と文書側で別々にこの長さまで書けます。
 * すべてのAI機能の先頭に付くので、長くするほど毎回の入力が増えます。
 */
export const MAX_AI_CONTEXT_CHARS = 4_000;

/** レビュアーが書く読み手の説明の長さ。組み立てにも、そのまま使うときにも同じ上限です。 */
export const MAX_PERSONA_INPUT_CHARS = 2_000;

/* ---- レビュースキル -------------------------------------------------- */

/** プロンプトへ載せるスキル本文の長さ。これを超えたスキルは末尾を落とします。 */
export const MAX_SKILL_INSTRUCTION_CHARS = 12_000;

/** 参照ファイルの長さ。1スキルの参照全体でこの長さまでを渡します。 */
export const MAX_SKILL_REFERENCE_CHARS = 12_000;

/** 参照として読むファイル数。これ以上置いてあるスキルは、名前の順に先頭から読みます。 */
export const MAX_SKILL_REFERENCE_FILES = 10;

/**
 * 一度に使えるスキルの数。観点を増やすほど1件あたりの読みは浅くなるので、
 * 「同時に持てる観点」として現実的なところで止めます。
 */
export const MAX_SELECTED_SKILLS = 5;

/* ---- コンテキストメモ ------------------------------------------------ */

/**
 * 1つの文書に残せるメモの数。超えた分を黙って捨てるのではなく、保存を断ります。
 *
 * 捨てるほうを選ばなかったのは、コメントと違ってメモは「全部読ませる前提」だからです。
 * 何件か落ちた状態でレビューを走らせると、レビュアーは残したはずの決定が
 * 効いていないことに気づけません。上限に当たったら、古いメモを消すか
 * まとめるかをレビュアーが決めます。
 */
export const MAX_CONTEXT_NOTES = 20;

/**
 * メモ1件の長さ。短いのはわざとです。
 * ここは経緯を語る場所ではなく、次に読むときへ渡す1行を置く場所です。
 * 長くするほど、すべてのAI機能の先頭に付く前提が重くなります。
 */
export const MAX_CONTEXT_NOTE_CHARS = 600;
